class CamRedirect : public zygisk::ModuleBase {
public:
    void onLoad(zygisk::Api *api, JNIEnv *env) override {
        api_ = api; env_ = env;
        g_api = api;
    }

    void preAppSpecialize(zygisk::AppSpecializeArgs *args) override {
        const char *proc = env_->GetStringUTFChars(args->nice_name, nullptr);
        std::string pkg(proc ? proc : "");
        env_->ReleaseStringUTFChars(args->nice_name, proc);
        auto colon = pkg.find(':'); if (colon != std::string::npos) pkg.resize(colon);
        g_self_pkg = pkg;

        std::string cfg = read_file(CONFIG_PATH);
        g_replacement_id = lookup(cfg, pkg);
        try { g_replacement_c1 = g_replacement_id.empty() ? -1 : std::stoi(g_replacement_id); }
        catch (...) { g_replacement_c1 = -1; }

        if (g_replacement_id.empty()) {
            api_->setOption(zygisk::DLCLOSE_MODULE_LIBRARY);  // not a target: vanish
        }
        target_ = !g_replacement_id.empty();
    }

    void postAppSpecialize(const zygisk::AppSpecializeArgs *) override {
        if (target_) install_hooks(env_);
    }

private:
    bool target_ = false;

    void install_hooks(JNIEnv *env) {
        shadowhook_init(SHADOWHOOK_MODE_UNIQUE, false);
        lsplant::InitInfo info{
            .inline_hooker = [](void *t, void *r) -> void * {
                return shadowhook_hook_func_addr(t, r, nullptr);
            },
            .inline_unhooker = [](void *t) -> bool {
                return shadowhook_unhook_func_addr(t) == 0;
            },
            .art_symbol_resolver = [](std::string_view s) -> void * {
                // Pull LSPlant's own sample resolver for your pinned NDK/OS
                // if hooks fail on your ROM — see LSPlant's example harness.
                void *h = dlsym(RTLD_DEFAULT, s.data());
                return h;
            },
        };
        if (!lsplant::Init(env, info)) { LOGW("lsplant init failed"); return; }

        jclass hooks = load_stub_class(env, app_classloader(env), "com.camtest.stub.Hooks");
        if (!hooks) return;

        JNINativeMethod natives[] = {
            {"remapCamera2",
             "(Landroid/hardware/camera2/CameraManager;Ljava/lang/String;)Ljava/lang/String;",
             (void *) Java_com_camtest_stub_Hooks_remapCamera2},
            {"remapCamera1", "(I)I",
             (void *) Java_com_camtest_stub_Hooks_remapCamera1},
        };
        env->RegisterNatives(hooks, natives, 2);

        // Camera1: open(int) and open()
        hook_method(env, "android/hardware/Camera", "open",
                    "(I)Landroid/hardware/Camera;", true,
                    hooks, "openCamera1Replacement", "(I)Landroid/hardware/Camera;", "backupOpen1");
        hook_method(env, "android/hardware/Camera", "open",
                    "()Landroid/hardware/Camera;", true,
                    hooks, "openCamera0Replacement", "()Landroid/hardware/Camera;", "backupOpen0");

        // Camera2: both overloads
        hook_method(env, "android/hardware/camera2/CameraManager", "openCamera",
                    "(Ljava/lang/String;Landroid/hardware/camera2/CameraDevice$StateCallback;Landroid/os/Handler;)V",
                    false, hooks, "openCamera2Replacement",
                    "(Landroid/hardware/camera2/CameraManager;Ljava/lang/String;"
                    "Landroid/hardware/camera2/CameraDevice$StateCallback;Landroid/os/Handler;)V",
                    "backupOpen2");
        hook_method(env, "android/hardware/camera2/CameraManager", "openCamera",
                    "(Ljava/lang/String;Ljava/util/concurrent/Executor;"
                    "Landroid/hardware/camera2/CameraDevice$StateCallback;)V",
                    false, hooks, "openCamera2ExecReplacement",
                    "(Landroid/hardware/camera2/CameraManager;Ljava/lang/String;"
                    "Ljava/util/concurrent/Executor;"
                    "Landroid/hardware/camera2/CameraDevice$StateCallback;)V",
                    "backupOpen2Exec");
    }

    zygisk::Api *api_{};
    JNIEnv *env_{};
    bool target_ = false;
};

